import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { generateLevel, validateLevel, findWordPaths, GENERATOR_VERSION } from '../dist/core/wordtiles-algorithm.js';
import { createAlgorithmSession, validateAlgorithmLevel } from '../dist/core/algorithm-v1-adapter.js';
import { freeze } from '../dist/core/rules.js';
import { checkV1Independently, permutations } from '../scripts/independent-v1-check.mjs';

const json = async path => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const dictionary = freeze(await json('../dist/dictionary-v1.json'));
const fixture = freeze(await json('../examples/seed_20261010.json'));
const sample = freeze(await json('../dist/sample.json'));
const budgets = { maxNodesPerAttempt:10000, maxAttempts:30, maxTotalNodes:300000 };
const flatSample = { ...structuredClone(fixture), letters:sample.board.letters, initialCounts:sample.board.counts,
  targets:sample.targets.map((t,i)=>({ id:`W${i}`, word:t.word, canonicalPath:t.path })) };

test('编译JS记录的源码哈希一致，不能拿旧编译结果验证新TS', async () => {
  const source=await readFile(new URL('../src/wordtiles-algorithm.ts',import.meta.url));
  const compiled=await readFile(new URL('../dist/core/wordtiles-algorithm.js',import.meta.url),'utf8');
  assert.ok(compiled.startsWith(`// Generated by scripts/build-algorithm.mjs; source SHA-256: ${createHash('sha256').update(source).digest('hex')}\n`));
});
test('原词库原样保留；新词库版本、词长分布与上传包一致', async () => {
  const old = await readFile(new URL('../dist/dictionary.json', import.meta.url));
  assert.equal(createHash('sha256').update(old).digest('hex'), '4555df73fa7f025174971035efaeb3386202f4a1e8dda187ecafb51a8e769760');
  assert.equal(dictionary.version, 'demo-test-20261010-v1');
  assert.equal(dictionary.words.length, 1602);
  assert.deepEqual([3,4,5].map(n=>dictionary.words.filter(w=>w.length===n).length), [286,612,704]);
});
test('最新编译源默认预算/seed20261010逐字段等于原JSON；重现关卡和统计', () => {
  const a = generateLevel(budgets, dictionary, 20261010);
  const b = generateLevel({}, dictionary, 20261010);
  assert.equal(GENERATOR_VERSION, 'backtrack-v1.0.0');
  assert.equal(a.ok, true); assert.deepEqual(a.level, fixture);
  assert.deepEqual(b, a);
  assert.equal(a.validation.statesChecked, 32);
  assert.deepEqual(a.dictionaryReport, { accepted:1602, countsByLength:{3:286,4:612,5:704}, duplicateCount:0, rejectedIndices:[] });
  assert.deepEqual(checkV1Independently(a.level,dictionary), { statesChecked:32 });
});
test('算法生成与导入共用新白名单；CLOTH缺失则必须拒绝', () => {
  const reduced = { ...dictionary, words:dictionary.words.filter(w=>w!=='CLOTH') };
  assert.equal(validateLevel(fixture,reduced).ok,false);
  assert.equal(validateAlgorithmLevel(fixture,reduced).valid,false);
  assert.throws(()=>createAlgorithmSession(fixture,reduced));
  assert.equal(validateAlgorithmLevel(fixture,dictionary).valid,true);
});
test('完整词库对象必需；字符串seed/负数/小数/越界/未知配置禁止', () => {
  for (const seed of ['20261010',-1,1.2,4294967296,NaN,null]) assert.equal(generateLevel({},dictionary,seed).code,'INVALID_INPUT');
  for (const config of [null,{rows:3},{wordLengths:[3,3,3,4,5]},{maxAttempts:0},{maxTotalNodes:1.5}])
    assert.equal(generateLevel(config,dictionary,0).code,'INVALID_INPUT');
  assert.equal(generateLevel({},dictionary.words,0).code,'INVALID_INPUT');
  assert.equal(validateLevel(fixture,dictionary.words).ok,false);
  for (const seed of [0,4294967295]) assert.equal(generateLevel({},dictionary,seed).ok,true);
});
test('词库不足、总预算耗尽、尝试耗尽、取消均返回失败，没有样例回退', () => {
  const results = [
    [generateLevel({}, {version:'short',words:['CAT']},0), 'DICTIONARY_INSUFFICIENT'],
    [generateLevel({maxNodesPerAttempt:1,maxAttempts:1,maxTotalNodes:1},dictionary,0), 'SEARCH_BUDGET_EXCEEDED'],
    [generateLevel({maxNodesPerAttempt:1,maxAttempts:1,maxTotalNodes:100},dictionary,0), 'SEARCH_ATTEMPTS_EXCEEDED'],
    [generateLevel({},dictionary,0,{isCancelled:()=>true}), 'CANCELLED'],
  ];
  for (const [result,code] of results) { assert.equal(result.ok,false); assert.equal(result.code,code); assert.ok(!('level' in result)); }
});
test('非法平铺JSON拒绝，保留目标唯一性/字母/路径/精确次数校验', () => {
  const changes = [l=>l.rows=4,l=>l.maxCellUses=4,l=>l.seed='20261010',l=>l.letters[0]=null,
    l=>l.initialCounts[0]=0,l=>l.initialCounts[0]++,l=>l.targets[0].canonicalPath=[8,4,2],
    l=>l.targets[1].id=l.targets[0].id,l=>l.targets[1]=structuredClone(l.targets[0]),
    l=>l.targets[0]='EAT',l=>l.targets={some:1},l=>delete l.generatorVersion];
  for (const change of changes) {
    const level=structuredClone(fixture); change(level);
    assert.equal(validateAlgorithmLevel(level,dictionary).valid,false);
    assert.throws(()=>createAlgorithmSession(level,dictionary));
  }
  for (const value of [null,[],false,'level',{}, {targets:['CAT']}]) assert.equal(validateAlgorithmLevel(value,dictionary).valid,false);
});
test('相同消耗集合的多方向允许；不同集合在V1导入时拒绝', () => {
  const report=validateLevel(flatSample,dictionary); assert.equal(report.ok,true);
  const eye=report.targets.find(t=>t.word==='EYE'); assert.equal(eye.pathCount,2); assert.equal(eye.consumptionSetCount,1);
  const bad=structuredClone(flatSample); bad.letters[6]='F';
  assert.equal(validateAlgorithmLevel(bad,dictionary).valid,false);
  assert.ok(new Set(findWordPaths(bad.letters,'FEE').map(path=>[...path].sort().join(','))).size > 1);
  const game=createAlgorithmSession(flatSample,dictionary);
  assert.equal(game.submit([4,3,0]).accepted,true);
});
test('新关卡全部120种顺序通过实际GameSession提交，初始JSON与游玩隔离', () => {
  let checked=0;
  for (const order of permutations(fixture.targets)) {
    const game=createAlgorithmSession(fixture,dictionary);
    for (const target of order) {
      assert.equal(game.submit(target.canonicalPath).accepted,true,target.word);
      assert.ok(game.counts.every(n=>n>=0)); assert.equal(game.audit(),true);
    }
    assert.equal(game.status,'won'); assert.deepEqual(game.counts,Array(9).fill(0));
    assert.deepEqual(game.exportInitial,fixture); assert.ok(Object.isFrozen(game.exportInitial.initialCounts));
    const restarted=createAlgorithmSession(game.exportInitial,dictionary);
    assert.deepEqual(restarted.counts,fixture.initialCounts); checked++;
  }
  assert.equal(checked,120);
});
test('原固定样例用新白名单仍可试玩，EYE正反/FEED前缀/错误输入保留次数', () => {
  const a=createAlgorithmSession(sample,dictionary), b=createAlgorithmSession(sample,dictionary);
  assert.equal(a.submit([0,3,4]).accepted,true); assert.equal(b.submit([4,3,0]).accepted,true);
  assert.deepEqual(a.counts,b.counts);
  const game=createAlgorithmSession(sample,dictionary);
  assert.equal(game.submit([1,4,7,8]).accepted,true); assert.deepEqual([...game.completed],['FEED']);
  const before=game.snapshot();
  for (const path of [[0,1,2],[1,4,7,8],[0,4,8],[1,4,1]]) { assert.equal(game.submit(path).accepted,false); assert.deepEqual(game.snapshot(),before); }
  assert.equal(game.submit([1,4,7]).accepted,true);
  for (const target of sample.targets.filter(t=>!game.completed.has(t.word))) assert.equal(game.submit(target.path).accepted,true);
  assert.equal(game.status,'won'); assert.deepEqual(game.exportInitial,sample);
});
test('独立找路不会跨空位、斜连、跨行或把空格当通配符', () => {
  assert.deepEqual(findWordPaths([null,null,null,null,null,null,null,null,null],'CAT'),[]);
  const paths=findWordPaths(fixture.letters,'EAT');
  assert.deepEqual(paths,[[8,5,2]]);
  const remaining=[...fixture.initialCounts]; remaining[5]=0;
  assert.deepEqual(findWordPaths(fixture.letters,'EAT',remaining),[]);
});
