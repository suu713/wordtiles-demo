import { readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import { createHash } from 'node:crypto';

// Node 24's TypeScript transform compiles parameter properties as well as types.
// The supplied TypeScript stays unchanged; browsers receive plain ES modules.
const source = await readFile(new URL('../src/wordtiles-algorithm.ts', import.meta.url), 'utf8');
const hash = createHash('sha256').update(source).digest('hex');
const javascript = stripTypeScriptTypes(source, { mode: 'transform' });
await writeFile(new URL('../dist/core/wordtiles-algorithm.js', import.meta.url),
  `// Generated by scripts/build-algorithm.mjs; source SHA-256: ${hash}\n${javascript}`);
console.log(`Compiled supplied algorithm, source SHA-256: ${hash}`);
